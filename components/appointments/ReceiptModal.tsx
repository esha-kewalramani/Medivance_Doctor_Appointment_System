"use client";
import { Printer } from "lucide-react";
import Modal from "@/components/ui/Modal";
import { useApp } from "@/hooks/useApp";
import { Appointment, Doctor } from "@/types";
import { fmtDate, fmtTime, money } from "@/lib/utilities";

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c] as string));

/** Opens a clean, standalone page and the print dialog (choose "Save as PDF" to download). */
function printReceipt(rows: [string, string][], ref: string, status: string, simulated: boolean) {
  const w = window.open("", "_blank", "width=820,height=900");
  if (!w) return false;
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>MEDIVANCE receipt ${esc(ref)}</title><style>
    *{box-sizing:border-box}body{font-family:Inter,Arial,sans-serif;color:#0a2848;margin:0;padding:40px}
    .wrap{max-width:680px;margin:0 auto;border:1px solid #bad4e2;border-radius:16px;padding:32px}
    h1{margin:0;font-family:Georgia,serif;font-size:28px;letter-spacing:.04em}h1 span{color:#0e8ca1}
    .sub{color:#546c85;font-size:13px;margin-top:4px}.top{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:2px solid #0e8ca1;padding-bottom:16px;margin-bottom:8px}
    .tag{border:1px solid #0e8ca1;color:#0e8ca1;border-radius:99px;padding:4px 12px;font-size:12px;font-weight:700;text-transform:uppercase}
    table{width:100%;border-collapse:collapse;margin-top:8px}td{padding:11px 4px;border-bottom:1px solid #e3eef4;font-size:14px;vertical-align:top}
    td:first-child{color:#546c85;width:38%}td:last-child{font-weight:600}
    .foot{margin-top:24px;font-size:12px;color:#546c85;line-height:1.6}
    @media print{body{padding:0}.wrap{border:0}}
  </style></head><body><div class="wrap">
    <div class="top"><div><h1>MEDI<span>VANCE</span></h1><div class="sub">Where Care Meets Tomorrow.</div></div><div class="tag">${esc(status)}</div></div>
    <h2 style="margin:16px 0 0;font-size:18px">Appointment Receipt</h2>
    <table>${rows.map(([k, v]) => `<tr><td>${esc(k)}</td><td>${esc(v)}</td></tr>`).join("")}</table>
    <p class="foot">Please arrive 10 minutes early and bring a valid ID. Keep this receipt for your records. This receipt was generated by the MEDIVANCE demo system.${simulated ? " The payment shown is a DEMO / SIMULATED payment: no real money was charged." : ""}</p>
  </div><script>window.onload=function(){setTimeout(function(){window.print()},250)}</script></body></html>`);
  w.document.close();
  return true;
}

export default function ReceiptModal({ a, doctor, open, onClose }: { a: Appointment; doctor?: Doctor; open: boolean; onClose: () => void }) {
  const { patientById, data } = useApp();
  const p = patientById(a.patientId);
  const pay = data.payments.find((x) => x.appointmentId === a.id && x.status === "paid");
  const hist = data.reschedules.filter((x) => x.appointmentId === a.id); // newest first
  const original = hist[hist.length - 1];
  const paidOn = pay ? new Date(pay.paidAt).toLocaleString("en-GB", { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" }) : "";
  const rows: [string, string][] = [
    ["Receipt / Ref no.", a.ref],
    ["Patient", (a.guestDetails?.name || p?.name) ?? "-"],
    ...(a.isGuest ? [["Booking Type", "Guest Booking (No login required)"]] as [string, string][] : []),
    ["Doctor", doctor?.name ?? "-"],
    ["Specialty", doctor?.specialization ?? "-"],
    ["Date", fmtDate(a.date)],
    ["Time", fmtTime(a.time)],
    ["Reason for visit", a.reason],
    ["Consultation fee", pay ? money(pay.amount) : doctor ? money(doctor.fee) : "-"],
    ["Booked on", fmtDate(a.createdAt.slice(0, 10))],
    ...(pay
      ? ([["Payment status", "PAID"], ["Transaction ID", pay.transactionId], ["Payment date", paidOn], ["Payment method", pay.method]] as [string, string][])
      : ([["Payment status", "NOT PAID - pay at the clinic (booked before online payment)"]] as [string, string][])),
    ...(original ? ([["Rescheduled by doctor", `originally ${fmtDate(original.oldDate)} at ${fmtTime(original.oldTime)}`]] as [string, string][]) : []),
  ];
  return (
    <Modal open={open} onClose={onClose} title="Appointment receipt">
      <div className="rounded-xl border border-line/50 p-4">
        <div className="flex items-start justify-between border-b border-line/40 pb-3">
          <div><p className="font-display text-xl font-extrabold">MEDI<span className="text-primary">VANCE</span></p><p className="text-xs text-muted">Where Care Meets Tomorrow.</p></div>
          <div className="flex flex-col items-end gap-1"><span className="badge badge-approved capitalize">{a.status}</span>{pay && <span className="badge badge-approved">PAID</span>}</div>
        </div>
        <dl className="divide-y divide-line/30 text-sm">
          {rows.map(([k, v]) => <div key={k} className="grid grid-cols-5 gap-2 py-2"><dt className="col-span-2 text-muted">{k}</dt><dd className="col-span-3 min-w-0 break-words font-semibold">{v}</dd></div>)}
        </dl>
      </div>
      <div className="mt-4 flex flex-wrap gap-2">
        <button className="btn-primary btn-sm" onClick={() => { if (!printReceipt(rows, a.ref, pay ? `${a.status} - PAID` : a.status, !!pay)) alert("Please allow pop-ups to print or save the receipt."); }}><Printer className="h-4 w-4" /> Print / Save as PDF</button>
        <button className="btn-ghost btn-sm" onClick={onClose}>Close</button>
      </div>
      <p className="mt-2 text-xs text-muted">Tip: in the print window choose “Save as PDF” as the printer to download a PDF.</p>
    </Modal>
  );
}
